// Generate Spanish MEANING clips for the radio via ElevenLabs — a warm
// Spanish-accent female voice ("Lisa") says the Spanish gloss of each item,
// so the radio duet is Joel (English) + her (Spanish) instead of robotic TTS.
//
//   node scripts/generate-es-audio.mjs           # generate missing clips
//   node scripts/generate-es-audio.mjs --force   # regenerate everything
//
// Clips land at public/audio/es/<key>.mp3 (same audioKey(id) scheme as the
// English clips). Rewrites lib/content/es-audio-manifest.ts.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_ITEMS } from "../lib/content/lessons.ts";
import { WORD_ES } from "../lib/content/word-es.ts";
import { audioKey } from "../lib/speech/audio-key.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ES_DIR = join(ROOT, "public", "audio", "es");
const MANIFEST = join(ROOT, "lib", "content", "es-audio-manifest.ts");
const API = "https://api.elevenlabs.io/v1";
const MODEL = "eleven_multilingual_v2";
const FORMAT = "mp3_44100_128";
const CONCURRENCY = 5;
const FORCE = process.argv.includes("--force");

// Lisa — Spanish accent, warm and youthful. The app's "Lumi" voice.
const VOICE_ID = "WLjZnm4PkNmYtNCyiCq8";

function loadEnv() {
  const env = { ...process.env };
  const file = join(ROOT, ".env.local");
  if (existsSync(file)) {
    for (const line of readFileSync(file, "utf8").split("\n")) {
      const m = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m && !env[m[1]]) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
  return env;
}

const env = loadEnv();
const API_KEY = env.ELEVENLABS_API_KEY;
if (!API_KEY) {
  console.error("Missing ELEVENLABS_API_KEY (env or .env.local).");
  process.exit(1);
}

async function synth(text) {
  const res = await fetch(`${API}/text-to-speech/${VOICE_ID}?output_format=${FORMAT}`, {
    method: "POST",
    headers: { "xi-api-key": API_KEY, "Content-Type": "application/json" },
    body: JSON.stringify({
      text,
      model_id: MODEL,
      language_code: "es",
      voice_settings: { stability: 0.5, similarity_boost: 0.75, style: 0, use_speaker_boost: true },
    }),
  });
  if (!res.ok) {
    let detail = res.statusText;
    try {
      detail = JSON.stringify(await res.json());
    } catch {}
    throw new Error(`${res.status} ${detail}`);
  }
  return Buffer.from(await res.arrayBuffer());
}

// Meaning text per item: authored meaning first, else the word gloss. For
// multi-sense glosses ("bate / murciélago"), speak the first sense only.
function meaningText(item) {
  const raw = item.meaning ?? WORD_ES[item.text.trim().toLowerCase()];
  if (!raw) return null;
  return raw.split("/")[0].split(",")[0].trim();
}

const byKey = new Map();
for (const item of ALL_ITEMS) {
  const m = meaningText(item);
  if (m) byKey.set(audioKey(item.id), { item, meaning: m });
}
const jobs = [...byKey.entries()].map(([key, v]) => ({ key, ...v, out: join(ES_DIR, `${key}.mp3`) }));
mkdirSync(ES_DIR, { recursive: true });

console.log(`Spanish meaning clips to consider: ${jobs.length}`);

let done = 0;
let made = 0;
let skipped = 0;
let failed = 0;

async function worker(queue) {
  for (;;) {
    const job = queue.shift();
    if (!job) return;
    if (!FORCE && existsSync(job.out)) {
      skipped++;
    } else {
      try {
        const buf = await synth(job.meaning);
        writeFileSync(job.out, buf);
        made++;
      } catch (e) {
        failed++;
        console.error(`  x ${job.meaning}: ${e.message}`);
      }
    }
    done++;
    if (done % 20 === 0 || done === jobs.length) {
      process.stdout.write(`\r  ${done}/${jobs.length} (made ${made}, skipped ${skipped}, failed ${failed})   `);
    }
  }
}

const queue = [...jobs];
await Promise.all(Array.from({ length: CONCURRENCY }, () => worker(queue)));
console.log("");

// Manifest: which keys have a Spanish clip on disk.
const have = jobs.filter((j) => existsSync(j.out)).map((j) => j.key).sort();
writeFileSync(
  MANIFEST,
  `// AUTO-GENERATED by scripts/generate-es-audio.mjs — do not edit by hand.
// Spanish meaning clips (public/audio/es/<key>.mp3), spoken by "Lisa".

export const ES_AUDIO_KEYS: string[] = ${JSON.stringify(have, null, 2)};
`,
);
console.log(`Manifest written: ${have.length} Spanish clips. made=${made} skipped=${skipped} failed=${failed}`);
if (failed > 0) process.exit(1);
